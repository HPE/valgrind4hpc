class LongRunningSubprocess():
    """Start a long running subprocess in another thread and kill it when finished."""

    def __init__(self, args, quiet = False) -> None:
        self.keep_running = True
        self.should_term = False
        self.should_kill = False
        self.wait_timeout = None
        self.subp = None

        stdout = subprocess.DEVNULL if quiet else None
        stderr = subprocess.DEVNULL if quiet else None
        self.subp = subprocess.Popen(args=args, stdout=stdout, stderr=stderr)

        self.terminate_cv = threading.Condition()

        self.thread = threading.Thread(target=self.watch_subprocess)
        self.thread.start()

    def watch_subprocess(self):
        # wait for terminate flag
        with self.terminate_cv:
            self.terminate_cv.wait_for(lambda: self.keep_running == False or self.subp.poll() is not None)

        # terminate
        if self.should_kill:
            self.subp.kill()
        elif self.should_term:
            self.subp.terminate()
        else:
            try:
                log.debug(f"Waiting {self.wait_timeout} seconds for subprocesses to end...")
                self.subp.wait(self.wait_timeout)
            except subprocess.TimeoutExpired:
                log.debug(f"Subprocess timeout expired, killing...")
                self.subp.kill()

    def is_alive(self):
        if self.subp:
            return self.subp.poll() == None
        else:
            return False

    def wait(self, timeout: int = None):
        self.keep_running = False
        self.wait_timeout = timeout
        with self.terminate_cv:
            self.terminate_cv.notify()
        log.debug("Joining thread (wait)")
        self.thread.join()
        self.wait_timeout = None

    def term(self):
        self.keep_running = False
        self.should_term = True
        with self.terminate_cv:
            self.terminate_cv.notify()
        log.debug("Joining thread (term)")
        self.thread.join()

    def kill(self):
        self.keep_running = False
        self.should_kill = True
        with self.terminate_cv:
            self.terminate_cv.notify()
        log.debug("Joining thread (kill)")
        self.thread.join()

    # "with LRSP() as p..."
    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        self.kill()

class DummyProcess(LongRunningSubprocess):
    """Dummy server for use inside of "with" statements when --manual-server is specified"""

    def __init__(self):
        self.keep_running = True

    def is_alive(self):
        return self.keep_running

    def wait(self, timeout: int = None):
        self.keep_running = False

    def term(self):
        self.keep_running = False

    def kill(self):
        self.keep_running = False

class SshContext():
    """Handles all remote testing actions."""

    # struct like classes to keep the number of arguments passed to the SshConext
    # constructor down. These classes should never get more complicated than a blob
    # of data or data generating functions. The data and functions in these classes
    # should only be used directly by SshContext.

    class ConnectionInfo():
        """Information on how to get to the remote machine."""

        def __init__(self, user: str, host: str, friendly_name: Union[str, None], port: int, local_key_path: Union[str, None]) -> None:
            """
            - user: remote username to log in with.
            - host: resolvable remote hostname.
            - friendly_name: optional. a more human friendly name for host. this
              name will be used for UI and logging.
            - port: port on which to start to the test server.
            - local_key_path: path on local (client) machine to install on *host*
              for future ssh communication and processing. If None, a key will
              be auto-generated by SshContext.
            """
            self.user = user
            self.host = host
            self.friendly_name = friendly_name # None is valid
            self.port = port
            # generate a random id to use for identifying the ssh key that may be generated for this session.
            # ensure length is a multiple of 5 so the "=" padding character is never used.
            self.local_key_id = base64.b32encode(bytearray(random.getrandbits(8) for _ in range(5))).decode()
            self.local_key_path = local_key_path # None is valid
            self.key_is_oneoff = False if local_key_path else True

    class TestPathsInfo():
        """Information describing where everything should be sourced from and installed to."""

        def __init__(self, local_remote_ttool_path: str,
            local_ttool_path: str, local_tlib_path: str, local_tests_path: Union[str, None],
            remote_tests_root: Union[str, None]) -> None:
            """
            - local_remote_ttool_path: path on local machine to remote_test_tool.py
            - local_ttool_path: path on local machine to test_tool.py
            - local_tlib_path: path on local machine to cdst_test directory
            - local_tests_path: path on local machine to a directory containing
              tests.py. If None, it is assumed that the tests will be downloaded
              from artifactory.
            - remote_tests_root: path on remote machine where all test related
              files will go. If None, default_tests_root_prefix() will be used.
            """
            self.local_remote_ttool_path = local_remote_ttool_path
            self.local_ttool_path = local_ttool_path
            self.local_tlib_path = local_tlib_path
            self.local_tests_path = local_tests_path
            self.remote_tests_root = remote_tests_root

        def default_tests_root_prefix(self):
            return "~/tmp/cdst_test_"

    class UaiInfo():
        """Information describing a UAI/NCN pair."""

        def __init__(self, ncn: str) -> None:
            self.ncn = ncn
            self.ncn_user = None
            self.uai_id = None # when SshContext creates a UAI, its id will be saved here.

    def __init__(self, connection_info: ConnectionInfo, test_paths_info: TestPathsInfo, uai_info: Union[UaiInfo, None],
                clean_old: bool, manual_server: bool, id_string: Union[str, None]):
        if id_string is not None:
            self.random_id = id_string
        else:
            self.random_id = datetime.datetime.now().strftime("%m%d%H%M")

        self.conn_i = connection_info
        self.paths_i = test_paths_info
        self.uai_i = uai_info # None is valid

        self.clean_old = clean_old
        self.manual_server = manual_server

        self.ssh_good = False # externally set to True after connection is verified

        if not self.paths_i.remote_tests_root:
            # generate one in ~/tmp
            self.paths_i.remote_tests_root = \
                f"{self.paths_i.default_tests_root_prefix()}{self.random_id}_{self.get_friendly_name()}"
        else:
            # create a new directory in the specified remote path
            passed_root = self.paths_i.remote_tests_root
            self.paths_i.remote_tests_root = passed_root + ("/" if not passed_root.endswith("/") else "") \
             + os.path.basename(self.paths_i.default_tests_root_prefix()) + self.random_id

        log.debug(f"Remote tests path: {self.paths_i.remote_tests_root}")

    # Install the ssh key located at self.conn_i.local_key_path onto the remote machine.
    # Returns True on success and False on failure.
    def install_ssh_key(self) -> bool:
        if not self.conn_i.local_key_path:
            log.error("Can't install ssh key: no local key path.")
            return False

        if not os.getenv(env.SSHPASS):
            log.info(f"(You can skip manual entry by setting {env.SSHPASS})")
            password = getpass.getpass(f"Enter dcldap password for {self.conn_i.user} (won't echo): ")
            os.environ[env.SSHPASS] = password

        log.info(f"Installing {self.conn_i.local_key_path} at {self.conn_i.user}@{self.conn_i.host}")

        # remove host from known hosts so there will be no complaining when we
        # try to connect
        home = os.getenv("HOME")
        if not home:
            return False
        if not successful_launch(["ssh-keygen", "-R", self.conn_i.host, "-f", f"{home}/.ssh/known_hosts"], quiet=True):
            log.warn("Failed to remove {self.host} from known hosts. Might jam when ssh thinks someone is doing something nasty.")

        methods = [
            ("expect", [files.scripts() + "/sshcopyid.expect", f"{self.conn_i.user}", f"{self.conn_i.host}", f"{self.conn_i.local_key_path}"]),
            ("sshpass", ["sshpass", "-e", "ssh-copy-id", "-i", self.conn_i.local_key_path, f"{self.conn_i.user}@{self.conn_i.host}"])
        ]

        for method in methods:
            if successful_launch(["which", method[0]], quiet=True):
                log.debug(f"Copying ssh key with {method[0]}")
                if not successful_launch(method[1], quiet=True):
                    log.error(f"Failed to ssh-copy-id ({method[0]})")
                    return False
                else:
                    return True

        all_methods = ", ".join([m[0] for m in methods])
        log.error(f"Failed to ssh-copy-id (no automatic method present on system, tried {all_methods})")
        return False

    # Test if we have a ssh key installed on the other machine. If not, install
    # one then verify the connection. Creates uais on applicable machines.
    # Returns True on success and False on failure.
    def setup_ssh_connectivity(self) -> bool:
        keystr = self.conn_i.local_key_path if self.conn_i.local_key_path else "(no key given)"
        log.debug(f"Testing ssh connectivity: {self.conn_i.host}, {keystr}")

        # create a uai if needed
        # this will change self.host to the newly created uai
        if self.uai_i and not self.create_uai():
            log.error("Couldn't create UAI.")
            return False

        # pingable?
        count = 3
        if self.uai_i: count = 45 # uais can take a bit to finish spinning up

        log.info("ping...")
        if not successful_launch(["ping", "-c", str(count), "-W", "1", self.conn_i.host], quiet=True):
            log.error(f"Couldn't ping {self.conn_i.host}.")
            return False

        if not self.conn_i.local_key_path:
            self.conn_i.local_key_path = self.get_one_off_local_key_path()
            # sets self.conn_i.key_is_oneoff to True

        # sshable?
        log.info("ssh...")
        if not self.launch_remotely("echo ssh connection good", quiet=True, timeout=30):
            if not self.install_ssh_key():
                log.error(f"Failed to install key {self.conn_i.local_key_path} on {self.conn_i.user}@{self.conn_i.host}.")
                return False

            if not self.launch_remotely("echo ssh connection good", quiet=True, timeout=30):
                log.error(f"Couldn't ssh to {self.conn_i.user}@{self.conn_i.host}.")
                return False

        # passed all tests!
        return True

    # Setup directories and deliver files and libraries to the remote machine.
    # Returns True on success and False on failure.
    def setup_remote_tests_root(self) -> bool:
        # our test root, after setup, should look something like this:
        # /test_dir
        #   |_ remote_test_tool.py
        #   |_ test_tool.py
        #   |_ /cdst_test/
        #   |_ /downloads/
        #   |_ /rpminstall/
        #   |_ /rpmdb/
        #   |_ /tests/ - might be created at rpm install time
        #   \_ /logs/

        if self.clean_old and not self.cleanup_old_test_directories():
            log.warn("Failed to clean up old test directories. Continuing...")

        log.info(f"Creating tests root at {self.paths_i.remote_tests_root}...")

        # make sure our test directories exist
        big_mkdir_command = f"mkdir -p {self.paths_i.remote_tests_root}"
        directories = ["downloads", "rpminstall", "rpmdb", "logs"]
        for d in directories:
            big_mkdir_command += f" {self.paths_i.remote_tests_root}/{d}"

        if not self.launch_remotely(big_mkdir_command, quiet=True):
            log.error(f"Failed to remotely create tests directories in {self.paths_i.remote_tests_root}")
            return False

        # ensure the testing library is there
        if not self.scp_push(self.paths_i.local_tlib_path, "/cdst_test", recursive=True):
            log.error(f"Failed to copy testing library ({self.paths_i.local_tlib_path}) to {self.conn_i.host}")
            return False

        # ensure python libraries are installed
        if not self.launch_remotely(f"python3 {self.paths_i.remote_tests_root}/cdst_test/bootstrap.py", quiet=True):
            log.error("Failed to install python libraries")
            return False

        # ensure the test tool is there
        if not self.scp_push(self.paths_i.local_ttool_path, "/test_tool.py"):
            log.error(f"Failed to copy testing library ({self.paths_i.local_ttool_path}) to {self.conn_i.host}")
            return False

        # ensure test server is there
        if not self.scp_push(self.paths_i.local_remote_ttool_path, "/remote_test_tool.py"):
            log.error(f"Failed to copy testing library ({self.paths_i.local_remote_ttool_path}) to {self.conn_i.host}")
            return False

        # ensure tests are there if given
        if self.paths_i.local_tests_path and not self.scp_push(self.paths_i.local_tests_path, "/tests", recursive=True):
            log.error(f"Failed to copy local tests path \"{self.paths_i.local_tests_path}\" to {self.conn_i.host}")
            return False

        return True

    # Find directories on the remote machine that match the basename of the
    # default test directory name and remove them if they are too old.
    # Returns True on success and False on failure.
    def cleanup_old_test_directories(self) -> bool:
        # find the test directory and move one level up
        to_clean = os.path.dirname(self.paths_i.remote_tests_root)
        if not to_clean:
            return False

        log.info(f"Cleaning up {to_clean}")
        # remove any old test directories older than a week
        # TODO: make the time window configurable?
        # will find everything that starts with "cdst_test_"
        startswith = os.path.basename(self.paths_i.default_tests_root_prefix())
        if not self.launch_remotely(f"find {to_clean} -maxdepth 1 -type d -name '{startswith}*' -user {self.conn_i.user} -mtime +3.5 -exec rm -rf {{}} +", quiet=True):
            log.warn("Failed to clean up")
            return False

        return True

    # Return prefex for all remote ssh commands
    def remote_launch_args(self, tty = False, timeout = 0) -> list:
        if not self.conn_i.local_key_path:
            raise RuntimeError()

        l = ["ssh", "-i", self.conn_i.local_key_path, "-o", "BatchMode=yes", f"{self.conn_i.user}@{self.conn_i.host}"]
        if tty:
            l.insert(1, "-t")

        timeo = ["timeout", str(timeout)] if timeout != 0 else []
        l = timeo + l

        return l

    # Run a command on the remote machine
    # Returns True on success and False on failure.
    def launch_remotely(self, command : str, tty = False, quiet = False, timeout = 0) -> bool:
        l = self.remote_launch_args(tty, timeout) + [command]
        return successful_launch(l, quiet)

    # Push files or directories to the remote machine. remote_dst is relative
    # to the remote testing directory and should start with /.
    # Returns True on success and False on failure.
    def scp_push(self, local_src, remote_dst = "", recursive = False) -> bool:
        if not self.conn_i.local_key_path:
            log.error("Can't scp_push: no local key path")
            return False

        if remote_dst and not remote_dst.startswith("/"):
            log.error("Can't scp_push: remote destination doesn't start with /")
            return False

        if recursive:
            local_src = local_src + ("/" if not local_src.endswith("/") else "")

        l = ["rsync", "-avL", "-e", f"ssh -i {self.conn_i.local_key_path}", local_src, f"{self.conn_i.user}@{self.conn_i.host}:{self.paths_i.remote_tests_root}{remote_dst}"]
        return successful_launch(l, True)

    # Pull files or directories from the remote machine. remote_src is relative
    # to the remote testing directory and should start with /.
    # Returns True on success and False on failure.
    def scp_pull(self, remote_src, local_dst, recursive = False) -> bool:
        if not self.conn_i.local_key_path:
            log.error("Can't scp_pull: no local key path")
            return False

        if remote_src and not remote_src.startswith("/"):
            log.error("Can't scp_pull: remote source doesn't start with /")
            return False

        if recursive:
            remote_src = remote_src + ("/" if not remote_src.endswith("/") else "")

        l = ["rsync", "-avL", "-e", f"ssh -i {self.conn_i.local_key_path}", f"{self.conn_i.user}@{self.conn_i.host}:{self.paths_i.remote_tests_root}{remote_src}", local_dst]
        return successful_launch(l, True)

    # Start an ssh tunnel mapping localhost:self.conn_i.port to remote:self.conn_i.port
    def start_ssh_tunnel(self) -> LongRunningSubprocess:
        if not self.conn_i.local_key_path:
            raise RuntimeError()

        if self.conn_i.host == socket.gethostname():
            log.debug("Avoiding ssh tunnel to self")
            return DummyProcess()

        args = ["ssh", "-i", f"{self.conn_i.local_key_path}", "-L", f"{self.conn_i.port}:localhost:{self.conn_i.port}", f"{self.conn_i.user}@{self.conn_i.host}", "-Nn"]
        return LongRunningSubprocess(args, True)

    # Get the name of the remote server in a form that makes sense for naming
    # things that humans will read.
    def get_friendly_name(self) -> str:
        if self.conn_i.friendly_name: return self.conn_i.friendly_name
        if self.uai_i: return self.uai_i.ncn
        return self.conn_i.host

    # Start the remote test tool in server mode on the remote machine
    def start_remote_server(self) -> LongRunningSubprocess:
        if self.manual_server:
            log.info("Manual server mode selected. Assuming server is already up.")
            return DummyProcess()

        # build launch string in parts for readability
        # make sure each line ends with a space to separate it from the next

        # cwd
        l = f"cd {self.paths_i.remote_tests_root} "
        # env vars
        # XXX: This doesn't work if remote user's login shell isn't bash
        l += f"&& {env.LIB_DIR}={self.remote_tests_root()} {env.WHEREAMI}={self.get_friendly_name()} {env.DEBUG}=1 {env.LOG_DIR}={self.paths_i.remote_tests_root}/logs "
        # launch server
        l += f"./remote_test_tool.py --server-port {self.conn_i.port} --log-mode"

        args = self.remote_launch_args() + [l]
        return LongRunningSubprocess(args, True)

    # Create a uai on remote machines that require one.
    # Returns True on success and False on failure.
    def create_uai(self) -> bool:
        if not self.uai_i:
            log.error("Can't create a UAI: no known uai info")
            return False

        log.info(f"Creating uai on {self.uai_i.ncn}...")

        # is the NCN reachable?
        if not successful_launch(["ping", "-c", "3", "-W", "1", self.uai_i.ncn], quiet=True):
            log.error(f"Couldn't ping {self.uai_i.ncn}.")
            return False

        if not os.getenv(env.SSHPASS):
            log.info(f"You can skip manual entry by setting {env.SSHPASS}.")
            os.environ[env.SSHPASS] = getpass.getpass(f"Enter dcldap password for {self.conn_i.user} (won't echo): ")
        if not os.getenv(env.NCN_USER):
            log.info(f"You can skip manual entry by setting {env.NCN_USER}.")
            os.environ[env.NCN_USER] = input(f"Enter username for {self.uai_i.ncn}: ")
        self.uai_i.ncn_user = os.getenv(env.NCN_USER)
        if not os.getenv(env.NCN_SSHPASS):
            log.info(f"You can skip manual entry by setting {env.NCN_SSHPASS}.")
            os.environ[env.NCN_SSHPASS] = getpass.getpass(f"Enter password for {self.uai_i.ncn_user}@{self.uai_i.ncn} (won't echo): ")

        if not self.conn_i.local_key_path:
            self.conn_i.local_key_path = self.get_one_off_local_key_path()
            # sets conn_i.key_is_oneoff to True

        pubkey_path = self.conn_i.local_key_path + ".pub"
        log.info(f"Sending {pubkey_path} to NCN ({self.uai_i.ncn})")
        if not os.path.isfile(pubkey_path):
            log.error(f"{pubkey_path} doesn't exist.")
            return False

        if not successful_launch(["which", "expect"], quiet=True):
            log.error("expect is required to be installed to create UAIs.")
            return False

        # temporarily set SSHPASS to NCN_SSHPASS for passworded SSH expect scripts
        old_sshpass = os.getenv(env.SSHPASS)
        os.environ[env.SSHPASS] = os.getenv(env.NCN_SSHPASS)

        log.info(f"Creating user directory on NCN ({self.uai_i.ncn})...")
        if not successful_launch([f"{files.scripts()}/passwordedssh.expect", self.uai_i.ncn_user, self.uai_i.ncn, f"mkdir -p /root/{self.conn_i.user}/config"], quiet=True):
            log.error(f"Failed to mkdir")
            return False

        log.info(f"Sending public key to NCN ({self.uai_i.ncn})...")
        if not successful_launch([f"{files.scripts()}/passwordedscp.expect", pubkey_path, f"{self.uai_i.ncn_user}@{self.uai_i.ncn}:/root/{self.conn_i.user}"], quiet=True):
            log.error(f"Failed to scp pubkey")
            return False

        # restore correct password vars
        os.environ[env.SSHPASS] = old_sshpass

        log.info(f"Creating UAI on NCN ({self.uai_i.ncn})...")
        # prompt should match the terminal prompt that will be seen upon login
        prompt = self.uai_i.ncn[self.uai_i.ncn.find("ncn-"):] + ":~ #"
        p = subprocess.run([f"{files.scripts()}/uai.expect", self.uai_i.ncn_user, self.uai_i.ncn, self.conn_i.user, f"/root/{self.conn_i.user}/{os.path.basename(pubkey_path)}", prompt],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE)

        if not p.returncode == 0:
            log.error(f"Failed to create UAI")
            log.info("Output:")
            for line in p.stdout.decode().splitlines():
                log.info(line)
            for line in p.stderr.decode().splitlines():
                log.info(line)
            return False

        # parse result
        uai_host = None
        for line in p.stdout.decode().splitlines():
            if line.startswith("uai_connect_string"):
                # remove prefix and last quote
                # e.g.: uai_connect_string = "ssh user@1.1.1.1"
                at = line.find("@")
                uai_host = line[at + 1:-1]
                log.info(f"Changed test host from \"{self.conn_i.host}\" to \"{uai_host}\"")
            elif line.startswith("uai_name"):
                self.uai_i.uai_id = line[line.find("\"") + 1:-1]

        if uai_host is None:
            log.error("Failed to parse host")
            log.info("UAI Process returned:")
            for line in p.stdout.decode().splitlines():
                log.info(f"{line}")
            return False

        if self.uai_i.uai_id is None:
            log.warn("Failed to parse UAI name, won't automatically clean it up")

        # change testing destination
        self.conn_i.host = uai_host

        return True

    # Permanently deletes the uai that was created with create_uai on the remote machine.
    # Returns True on success and False on failure.
    def delete_uai(self):
        if self.uai_i.uai_id is None:
            log.error("No UAI id to be found")
            return False

        # TODO automate this
        if not self.uai_i.ncn_user: self.uai_i.ncn_user = input(f"Enter username for {self.uai_i.ncn}: ")
        if not os.getenv(env.NCN_SSHPASS):
            log.info(f"You can skip manual entry by setting {env.NCN_SSHPASS}.")
            os.environ[env.NCN_SSHPASS] = getpass.getpass(f"Enter password for {self.uai_i.ncn_user}@{self.uai_i.ncn} (won't echo): ")

        old_sshpass = os.getenv(env.SSHPASS)
        os.environ[env.SSHPASS] = os.getenv(env.NCN_SSHPASS)

        log.info(f"Deleting UAI made on {self.uai_i.ncn}...")
        if not successful_launch([f"{files.scripts()}/passwordedssh.expect", self.uai_i.ncn_user, self.uai_i.ncn, f"export CRAY_CONFIG_DIR=/root/{self.conn_i.user}/config && cray uas delete --uai-list {self.uai_i.uai_id}"], quiet=True):
            log.error(f"Failed to delete UAI")
            return False

        log.info("Successfully deleted UAI.")

        pub_key_fname = os.path.basename(self.conn_i.local_key_path) + ".pub"
        pub_key_path = f"/root/{self.conn_i.user}/{pub_key_fname}"
        log.info(f"Deleting public key {pub_key_path} on {self.uai_i.ncn}...")
        if not successful_launch([f"{files.scripts()}/passwordedssh.expect", self.uai_i.ncn_user, self.uai_i.ncn, f"rm {pub_key_path}"], quiet=True):
            log.warn(f"Failed to delete remote {pub_key_path}.")
        else:
            log.info("Successfully deleted public key.")

        if old_sshpass: os.environ[env.SSHPASS] = old_sshpass

        return True

    # Return local key path pointing to ssh key used by this context. If such a
    # key doesn't exist, generate one. Returns None on error.
    def get_one_off_local_key_path(self) -> str:
        log.debug("get_one_off_local_key_path")

        if self.conn_i.local_key_path:
            log.debug("get_one_off_local_key_path returned cached key")
            return self.conn_i.local_key_path

        home = os.environ["HOME"]
        filename = "cdst_test_key_" + self.random_id + "_" + self.conn_i.local_key_id
        self.conn_i.local_key_path = home + "/.ssh/" + filename
        self.conn_i.key_is_oneoff = True

        log.info("Generating one off ssh key...")

        if os.path.isfile(self.conn_i.local_key_path):
            log.warn(f"Deleting old key file {self.conn_i.local_key_path}")
            os.unlink(self.conn_i.local_key_path)

        if not successful_launch(["ssh-keygen", "-q", "-t", "rsa", "-b", "2048", "-f", self.conn_i.local_key_path, "-N", "", "-C", f"{ONE_OFF_KEY_COMMENT} (id {self.conn_i.local_key_id})"]):
            log.error("Failed to generate key file")
            return None

        return self.conn_i.local_key_path

    # Clean up any persistent files or uais left by this context.
    def cleanup(self) -> None:
        if self.uai_i and not self.delete_uai():
            log.warn(f"Failed to delete uai at {self.host}")

        if self.conn_i.key_is_oneoff and self.conn_i.local_key_path and os.path.isfile(self.conn_i.local_key_path):
            log.info(f"Removing one-off key: {self.conn_i.local_key_path}")
            try:
                os.unlink(self.conn_i.local_key_path)
            except FileNotFoundError:
                pass # ok

            try:
                os.unlink(self.conn_i.local_key_path + ".pub")
            except FileNotFoundError:
                pass # ok

    def host(self):
        return self.conn_i.host

    def port(self):
        return self.conn_i.port

    def remote_tests_root(self):
        return self.paths_i.remote_tests_root
